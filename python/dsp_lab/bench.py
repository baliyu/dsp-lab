"""Stage 2 benchmark support: writes the test vectors and coefficients as a C header, works out the checksum (CRC-32) every output must have,
and checks a log printed by the device (or by the host build) against those checksums.

    PYTHONPATH=python python -m dsp_lab.bench gen bench/core/bench_data.h
    PYTHONPATH=python python -m dsp_lab.bench check device.log

The expected checksums come from the integer model (python/dsp_lab/model.py), not from the C code, so the device is compared with the specification.
Built with AI assistance (Claude)."""
from __future__ import annotations

import re
import sys
import zlib
from pathlib import Path

import numpy as np

from dsp_lab import design, model, vectors

FS = 8000.0
N = 2000                       # samples per test vector
SECTIONS = 2                   # 4th-order Butterworth = 2 biquad sections
TAPS = 31
FILTER_BQ = "biquad2_lp1000"
FILTER_FIR = "fir31_lp1000"
FILTERS = (FILTER_BQ, FILTER_FIR)
HEADER_NAME = "bench_data.h"


def crc32_i16(samples) -> int:
    """CRC-32 (the zlib / IEEE one) of the samples as little-endian 16-bit integers."""
    return zlib.crc32(np.asarray(samples, dtype="<i2").tobytes()) & 0xFFFFFFFF


def config():
    q = design.quantise_sos(design.butter_sos(FS, 1000, 4, "lowpass"))
    fir = design.fir_lowpass_q15(FS, 1000, TAPS)
    assert len(q) == SECTIONS and len(fir) == TAPS
    return q, fir, vectors.make_vectors(FS, N)


def expected() -> dict[tuple[str, str], int]:
    """(filter, vector) -> CRC-32 of the model's output."""
    q, fir, vec = config()
    out = {}
    for name, x in vec.items():
        out[(FILTER_BQ, name)] = crc32_i16(model.biquad_cascade(q, x))
        out[(FILTER_FIR, name)] = crc32_i16(model.fir(fir, x))
    return out


def _rows(values, per_line=12, indent="    "):
    vals = [str(int(v)) for v in values]
    return ",\n".join(indent + ", ".join(vals[i:i + per_line]) for i in range(0, len(vals), per_line))


def render_header() -> str:
    q, fir, vec = config()
    exp = expected()
    names = list(vec)
    L = []
    L.append("/* GENERATED by python/dsp_lab/bench.py: do not edit. Regenerate with:  python -m dsp_lab.bench gen bench/core/bench_data.h\n"
             "   Samples are int16; the checksums are CRC-32 (IEEE) over the output as little-endian 16-bit integers. */")
    L.append("#ifndef BENCH_DATA_H\n#define BENCH_DATA_H\n\n#include <stdint.h>\n")
    L.append(f"#define BENCH_N {N}u\n#define BENCH_NVEC {len(names)}u\n#define BENCH_SECTIONS {SECTIONS}u\n#define BENCH_TAPS {TAPS}u\n")
    L.append("#define BENCH_FILTER_BQ \"%s\"\n#define BENCH_FILTER_FIR \"%s\"\n" % (FILTER_BQ, FILTER_FIR))
    L.append("static const char *const bench_vec_name[BENCH_NVEC] = {\n    " + ", ".join(f'"{n}"' for n in names) + "\n};\n")
    L.append("/* b0, b1, b2, a1, a2 in Q2.14, one row per section */\nstatic const int16_t bench_bq_coefs[BENCH_SECTIONS][5] = {\n"
             + ",\n".join("    {" + ", ".join(str(v) for v in s) + "}" for s in q) + "\n};\n")
    L.append("/* Q15 */\nstatic const int16_t bench_fir_coefs[BENCH_TAPS] = {\n" + _rows(fir) + "\n};\n")
    for tag, f in (("bq", FILTER_BQ), ("fir", FILTER_FIR)):
        L.append(f"static const uint32_t bench_expect_{tag}[BENCH_NVEC] = {{\n    "
                 + ", ".join("0x%08xu" % exp[(f, n)] for n in names) + "\n};\n")
    body = []
    for n in names:
        body.append(f"    {{ /* {n} */\n{_rows(vec[n], indent='        ')}\n    }}")
    L.append("static const int16_t bench_vec[BENCH_NVEC][BENCH_N] = {\n" + ",\n".join(body) + "\n};\n")
    L.append("#endif")
    return "\n".join(L) + "\n"


# ---- reading a log ----------------------------------------------------------------------------------------------------------------------

RESULT = re.compile(r"^RESULT (\S+) (\S+) n=(\d+) crc=([0-9a-f]{8}) expect=([0-9a-f]{8}) ok=([01]) cyc_min=(\d+) cyc_max=(\d+)\s*$")
BANNER = re.compile(r"^BENCH 1 n=(\d+) vectors=(\d+) sections=(\d+) taps=(\d+) reps=(\d+)\s*$")
SUMMARY = re.compile(r"^SUMMARY runs=(\d+) failed=(\d+)\s*$")
OVERHEAD = re.compile(r"^OVERHEAD cyc_min=(\d+)\s*$")
ENV = re.compile(r"^ENV (\S+) (.*?)\s*$")


class Run:
    def __init__(self, banner):
        self.banner = banner
        self.rows: list[tuple] = []
        self.overhead = None
        self.summary = None


def parse_log(text: str):
    """Returns (runs, env, ignored_lines). A run starts at a BENCH line; only runs that reach their SUMMARY line are complete."""
    runs: list[Run] = []
    env: dict[str, str] = {}
    cur = None
    ignored = 0
    for raw in text.splitlines():
        line = raw.strip("\r\n ")
        if m := BANNER.match(line):
            cur = Run(tuple(int(g) for g in m.groups()))
            runs.append(cur)
        elif m := ENV.match(line):
            env[m.group(1)] = m.group(2)
        elif cur is None:
            ignored += 1
        elif m := RESULT.match(line):
            f, v, n, crc, exp, ok, lo, hi = m.groups()
            cur.rows.append((f, v, int(n), int(crc, 16), int(exp, 16), int(ok), int(lo), int(hi)))
        elif m := OVERHEAD.match(line):
            cur.overhead = int(m.group(1))
        elif m := SUMMARY.match(line):
            cur.summary = (int(m.group(1)), int(m.group(2)))
        else:
            ignored += 1
    return runs, env, ignored


def check(text: str):
    """Returns (problems, report_lines). No problems means every checksum matched the model in every complete run."""
    exp = expected()
    names = list(vectors.make_vectors(FS, N))
    want = {(f, v) for f in FILTERS for v in names}
    runs, env, _ = parse_log(text)
    problems: list[str] = []
    complete = [r for r in runs if r.summary is not None]
    if not complete:
        return ["no complete run in the log (no BENCH ... SUMMARY block)"], []
    for i, r in enumerate(complete, 1):
        tag = f"run {i}"
        if r.banner[:4] != (N, len(names), SECTIONS, TAPS):
            problems.append(f"{tag}: banner {r.banner[:4]} does not match this repository's configuration {(N, len(names), SECTIONS, TAPS)}")
        seen = [(row[0], row[1]) for row in r.rows]
        if len(seen) != len(set(seen)):
            problems.append(f"{tag}: a (filter, vector) pair appears twice")
        if set(seen) != want:
            problems.append(f"{tag}: missing {sorted(want - set(seen))} / unexpected {sorted(set(seen) - want)}")
        for f, v, n, crc, e, ok, lo, hi in r.rows:
            if n != N:
                problems.append(f"{tag}: {f}/{v}: n={n}, expected {N}")
            if (f, v) in exp and crc != exp[(f, v)]:
                problems.append(f"{tag}: {f}/{v}: device crc {crc:08x} but the model gives {exp[(f, v)]:08x}")
            if (f, v) in exp and e != exp[(f, v)]:
                problems.append(f"{tag}: {f}/{v}: the device's embedded expectation {e:08x} differs from the model {exp[(f, v)]:08x} (stale header?)")
            if not ok:
                problems.append(f"{tag}: {f}/{v}: the device itself reported ok=0")
            if lo > hi or lo == 0:
                problems.append(f"{tag}: {f}/{v}: implausible cycle counts {lo}..{hi}")
        runs_n, failed = r.summary
        if runs_n != len(r.rows) or failed != 0:
            problems.append(f"{tag}: SUMMARY says runs={runs_n} failed={failed}; {len(r.rows)} result lines")
    rep = []
    last = complete[-1]
    rep.append(f"{len(complete)} complete run(s) in the log; checksums {'ALL MATCH the model' if not problems else 'DO NOT ALL MATCH'}.")
    for k in sorted(env):
        rep.append(f"  env {k}: {env[k]}")
    if last.overhead is not None:
        rep.append(f"  empty-region overhead (two counter reads): {last.overhead} cycles per measured block")
    rep.append(f"  cycles per sample (minimum over {last.banner[4]} repeats; block of {N} samples; last run):")
    for f in FILTERS:
        rows = [row for row in last.rows if row[0] == f]
        for row in rows:
            rep.append(f"    {f:15s} {row[1]:17s} {row[6] / row[2]:8.2f}   (max over repeats {row[7] / row[2]:.2f})")
        if rows:
            rep.append(f"    {f:15s} {'mean of vectors':17s} {sum(r_[6] / r_[2] for r_ in rows) / len(rows):8.2f}")
    if len(complete) > 1:
        spread = max(abs(a[6] - b[6]) for a, b in zip(complete[0].rows, complete[-1].rows)) if len(complete[0].rows) == len(complete[-1].rows) else None
        rep.append(f"  largest change in a block's minimum cycle count, first run to last run: {spread}")
    return problems, rep


def main(argv: list[str]) -> int:
    if len(argv) == 3 and argv[1] == "gen":
        Path(argv[2]).write_text(render_header(), newline="\n")
        print(f"wrote {argv[2]}")
        return 0
    if len(argv) == 3 and argv[1] == "check":
        problems, rep = check(Path(argv[2]).read_text(errors="replace"))
        print("\n".join(rep))
        if problems:
            print("\nPROBLEMS:")
            print("\n".join("  - " + p for p in problems))
            return 1
        print("\nPASS: the device output is bit-identical to the model (CRC-32 of every output block).")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
